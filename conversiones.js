// Conversión de distancia

export function metrosAKilometros(metros) {
  return metros / 1000;
}

export function kilometrosAMetros(kilometros) {
  return kilometros * 1000;
}

export function metrosAMillas(metros) {
  return metros / 1609.34;
}

export function millasAMetros(millas) {
  return millas * 1609.34;
}

export function kilometrosAMillas(kilometros) {
  return kilometros / 1.60934;
}

export function millasAKilometros(millas) {
  return millas * 1.60934;
}

// Conversión de peso

export function gramosAKilogramos(gramos) {
  return gramos / 1000;
}

export function kilogramosAGramos(kilogramos) {
  return kilogramos * 1000;
}

export function gramosALibras(gramos) {
  return gramos / 453.592;
}

export function librasAGramos(libras) {
  return libras * 453.592;
}

export function kilogramosALibras(kilogramos) {
  return kilogramos * 2.20462;
}

export function librasAKilogramos(libras) {
  return libras / 2.20462;
}